#!/usr/bin/env bun
// Generates ui/src/api/protocol.gen.ts, the TypeScript types of the command and query API, from
// the published JSON Schema (schema/api/protocol.schema.json, API-02), so that the UI client
// (UI-01) never drifts from the core. `--check` fails when the committed file is stale; CI runs it.
// Usage: bun scripts/generate-api-types.ts [--check] [repo-root]

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

export const SCHEMA_FILE = "schema/api/protocol.schema.json";
export const OUTPUT_FILE = "ui/src/api/protocol.gen.ts";

type Schema = { [keyword: string]: unknown };

// Keywords that decide the TypeScript type. A $ref, a const or a union decides it alone, so it
// cannot be combined with another of them: the generator would have to drop one.
const SHAPING = ["type", "properties", "required", "additionalProperties", "items", "prefixItems", "$ref", "const", "anyOf", "oneOf"];
const ALONE = ["$ref", "const", "anyOf", "oneOf"];
// Keywords that narrow values without changing their TypeScript type: the server checks them.
const NARROWING = new Set(["description", "pattern", "minimum", "maximum", "uniqueItems", "minItems"]);
const SUPPORTED = new Set([
  ...NARROWING,
  "type",
  "properties",
  "required",
  "additionalProperties",
  "items",
  "prefixItems",
  "$ref",
  "const",
  "anyOf",
  "oneOf",
]);
// The $defs that are not shared types: the commands, the queries and the entity schema, which
// no command or query refers to.
const NOT_SHARED = new Set(["commands", "queries", "entities"]);
const IDENTIFIER = /^[A-Za-z_$][\w$]*$/;
const HEADER = `// Generated by scripts/generate-api-types.ts from ${SCHEMA_FILE}. Do not edit: run
// \`bun scripts/generate-api-types.ts\` after changing the API.
`;

const isSchema = (value: unknown): value is Schema =>
  typeof value === "object" && value !== null && !Array.isArray(value);

function asSchema(value: unknown, where: string): Schema {
  if (!isSchema(value)) throw new Error(`${where}: expected a schema object`);
  return value;
}

const key = (name: string): string => (IDENTIFIER.test(name) ? name : JSON.stringify(name));

const doc = (schema: Schema, indent: string): string =>
  typeof schema.description === "string" ? `${indent}/** ${schema.description} */\n` : "";

function objectType(schema: Schema, where: string): string {
  if (schema.additionalProperties !== false) {
    throw new Error(`${where}: objects must set "additionalProperties": false`);
  }
  const properties = asSchema(schema.properties ?? {}, `${where}.properties`);
  const required = new Set(Array.isArray(schema.required) ? schema.required : []);
  const members = Object.entries(properties).map(([name, property]) => {
    const optional = required.has(name) ? "" : "?";
    return `${key(name)}${optional}: ${typeOf(property, `${where}.${name}`)}`;
  });
  return members.length === 0 ? "Record<string, never>" : `{ ${members.join("; ")} }`;
}

function arrayType(schema: Schema, where: string): string {
  if (Array.isArray(schema.prefixItems)) {
    if (schema.items !== false || schema.minItems !== schema.prefixItems.length) {
      throw new Error(`${where}: tuples must set "items": false and "minItems" to their length`);
    }
    const items = schema.prefixItems.map((item, index) => typeOf(item, `${where}[${index}]`));
    return `[${items.join(", ")}]`;
  }
  return `Array<${typeOf(schema.items, `${where}.items`)}>`;
}

/** The TypeScript type of `schema`; `where` names it in errors. */
export function typeOf(value: unknown, where: string): string {
  const schema = asSchema(value, where);
  const unsupported = Object.keys(schema).filter((keyword) => !SUPPORTED.has(keyword));
  if (unsupported.length > 0) {
    throw new Error(`${where}: unsupported JSON Schema keyword(s): ${unsupported.join(", ")}`);
  }
  const shaping = SHAPING.filter((keyword) => keyword in schema);
  if (shaping.length > 1 && shaping.some((keyword) => ALONE.includes(keyword))) {
    throw new Error(`${where}: cannot combine ${shaping.join(", ")}`);
  }
  if (typeof schema.$ref === "string") {
    const match = /^#\/\$defs\/([A-Za-z]\w*)$/.exec(schema.$ref);
    if (match?.[1] === undefined) throw new Error(`${where}: unsupported $ref ${schema.$ref}`);
    return match[1];
  }
  if ("const" in schema) return JSON.stringify(schema.const);
  const variants = schema.anyOf ?? schema.oneOf;
  if (Array.isArray(variants)) {
    return variants.map((variant, index) => typeOf(variant, `${where}|${index}`)).join(" | ");
  }
  switch (schema.type) {
    case "string":
      return "string";
    case "integer":
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "null":
      return "null";
    case "array":
      return arrayType(schema, where);
    case "object":
      return objectType(schema, where);
    default:
      throw new Error(`${where}: unsupported type ${JSON.stringify(schema.type)}`);
  }
}

/** One member of the `Commands` or `Queries` interface, from a command or query definition. */
function method(name: string, value: unknown): string {
  const where = `$defs.${name}`;
  const definition = asSchema(value, where);
  const properties = asSchema(definition.properties, `${where}.properties`);
  const declared = asSchema(properties.name, `${where}.name`).const;
  if (declared !== name) {
    throw new Error(`${where}: is named ${JSON.stringify(declared)}; versioned names are not supported yet`);
  }
  const params = typeOf(properties.params, `${where}.params`);
  const result = typeOf(properties.result, `${where}.result`);
  return `${doc(definition, "  ")}  ${key(name)}: { params: ${params}; result: ${result} };\n`;
}

function methods(title: string, summary: string, value: unknown, where: string): string {
  const members = Object.entries(asSchema(value, where)).map(([name, definition]) =>
    method(name, definition),
  );
  return `\n/** ${summary} */\nexport interface ${title} {\n${members.join("")}}\n`;
}

/** The contents of protocol.gen.ts for the protocol schema `schema`. */
export function generate(schema: unknown): string {
  const defs = asSchema(asSchema(schema, "schema").$defs, "$defs");
  const shared = Object.entries(defs)
    .filter(([name]) => !NOT_SHARED.has(name))
    .map(([name, value]) => {
      const where = `$defs.${name}`;
      return `\n${doc(asSchema(value, where), "")}export type ${name} = ${typeOf(value, where)};\n`;
    });
  return [
    HEADER,
    ...shared,
    methods("Commands", "Every command: its parameters and its result.", defs.commands, "$defs.commands"),
    methods("Queries", "Every query: its parameters and its result.", defs.queries, "$defs.queries"),
  ].join("");
}

/** Runs with the command-line arguments `args`: `[--check] [repo-root]`. */
export function main(args: string[]): number {
  const check = args.includes("--check");
  const root = args.find((arg) => arg !== "--check") ?? process.cwd();
  const schema: unknown = JSON.parse(readFileSync(join(root, SCHEMA_FILE), "utf8"));
  const generated = generate(schema);
  const output = join(root, OUTPUT_FILE);
  if (!check) {
    writeFileSync(output, generated);
    console.log(`Wrote ${OUTPUT_FILE}.`);
    return 0;
  }
  let committed = "";
  try {
    committed = readFileSync(output, "utf8");
  } catch {
    // A missing file is stale too.
  }
  if (committed === generated) {
    console.log(`${OUTPUT_FILE} is up to date.`);
    return 0;
  }
  console.error(`${OUTPUT_FILE} is stale. Run: bun scripts/generate-api-types.ts`);
  return 1;
}

if (import.meta.main) process.exit(main(process.argv.slice(2)));
