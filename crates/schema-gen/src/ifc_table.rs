//! IFC mapping table emitter (CORE-10): the `[ifc]` section of every entity as a Markdown table,
//! published for the core namespace as `docs/dev/ifc-mapping.md`.

use std::fmt::Write as _;

use schema::{Entity, Namespace};

/// Emits the IFC mapping table of a namespace as a Markdown page ending with a newline.
///
/// Entities come sorted by name, one row each. Every entity has a mapping once the namespace is
/// validated (CORE-10); a missing one would show as an empty IFC entity cell. The same namespace
/// always gives the same text.
#[must_use]
pub fn emit_ifc_mapping(namespace: &Namespace) -> String {
    let mut out = format!(
        "<!-- @generated by schema-gen from the schema definitions. Do not edit. -->\n\n\
         # IFC mapping of the `{}` schema\n\n\
         How each entity of version {} of the `{}` schema maps onto IFC 4.3 (CORE-10). The rows \
         come from the `[ifc]` section of each definition (ADR 0002).\n\n\
         Checks: validation rejects an entity with no mapping; `cargo test -p interop-ifc` \
         checks every name against the IFC 4.3 schema; `cargo test -p schema-gen` fails when \
         this page is out of date, and `UPDATE_SNAPSHOTS=1 cargo test -p schema-gen` \
         regenerates it.\n\n",
        namespace.name, namespace.version, namespace.name
    );
    if namespace.entities.is_empty() {
        out.push_str("The schema defines no entity yet.\n");
        return out;
    }
    out.push_str(
        "| Entity | Kind | IFC entity | Predefined type | Object type | IFC type entity |\n\
         | --- | --- | --- | --- | --- | --- |\n",
    );
    for entity in namespace.entities.values() {
        row(&mut out, entity);
    }
    out
}

fn row(out: &mut String, entity: &Entity) {
    let ifc = entity.ifc.as_ref();
    let code =
        |value: Option<&String>| value.map_or_else(String::new, |text| format!("`{}`", cell(text)));
    // Writing to a String cannot fail.
    let _ = writeln!(
        out,
        "| `{}` | {} | {} | {} | {} | {} |",
        entity.name,
        entity.kind.name(),
        code(ifc.map(|ifc| &ifc.entity)),
        code(ifc.and_then(|ifc| ifc.predefined_type.as_ref())),
        code(ifc.and_then(|ifc| ifc.object_type.as_ref())),
        code(ifc.and_then(|ifc| ifc.type_entity.as_ref())),
    );
}

/// Text made safe for a code span in a table cell; an object type is free text. Backslashes
/// are literal in a code span, and GitHub reads `\|` there as a pipe that does not end the cell.
fn cell(text: &str) -> String {
    text.replace('|', "\\|")
        .replace('`', "'")
        .replace(['\n', '\r'], " ")
}

#[cfg(test)]
mod tests {
    use super::cell;

    #[test]
    fn escapes_what_would_break_a_table_cell() {
        assert_eq!(cell("a|b\\c`d\ne\rf"), "a\\|b\\c'd e f");
    }
}
