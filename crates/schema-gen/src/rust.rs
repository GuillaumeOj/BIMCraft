//! Rust emitter: one serde struct per entity, per entity type and per property set.
//!
//! The output is plain data for now; once attribute tables exist (CORE-05) the same entry point
//! will emit typed views over them instead (ADR 0002). It is written directly in the layout
//! rustfmt produces, so it passes `rustfmt --check` without running rustfmt at build time.

use std::collections::BTreeSet;
use std::fmt::Write as _;

use schema::{
    Attribute, Cardinality, Entity, Namespace, Placement, Presence, PropertySet, Role, Value,
    ValueType,
};

use crate::{Error, ErrorKind};

/// Choices the emitted code depends on.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct RustOptions {
    /// Path of the type that identifies objects, used for `ref:` values, such as
    /// `core_model::EntityId`.
    pub id_type: String,
}

/// Lints the emitted structs allow, because their docs and names come from the schema.
const ALLOWED_LINTS: &str = "#[allow(
    clippy::doc_markdown,
    clippy::struct_excessive_bools,
    clippy::struct_field_names,
    reason = \"docs and names come from the schema definitions, not from Rust authors\"
)]";

/// Rust keywords that cannot be used even as raw identifiers.
const NOT_RAW: [&str; 4] = ["crate", "self", "super", "Self"];

/// Emits the Rust types of a namespace.
///
/// The namespace is validated first, so the output only depends on valid input. Entities and
/// property sets come in name order and attributes in declaration order, so the same namespace
/// always gives the same code.
///
/// # Errors
///
/// Returns validation errors, and names that cannot become distinct Rust identifiers.
pub fn emit_rust(namespace: &Namespace, options: &RustOptions) -> Result<String, Vec<Error>> {
    schema::validate(namespace).map_err(|errors| {
        errors
            .into_iter()
            .map(|error| Error::new(ErrorKind::Validation(Box::new(error))))
            .collect::<Vec<_>>()
    })?;
    let structs = plan(namespace, options);
    check_names(&structs)?;
    let mut out = format!(
        "// @generated by schema-gen from the `{}` schema, version {}. Do not edit.\n",
        namespace.name, namespace.version
    );
    for item in &structs {
        out.push('\n');
        write_struct(&mut out, item);
    }
    Ok(out)
}

/// A struct to emit.
struct Struct {
    name: String,
    doc: Vec<String>,
    fields: Vec<Field>,
}

struct Field {
    /// Name in the schema, kept in serialized data.
    schema_name: String,
    /// Rust identifier, without the `r#` prefix.
    name: String,
    doc: Vec<String>,
    ty: String,
    kind: FieldKind,
}

enum FieldKind {
    /// Always present.
    Required,
    /// Filled with the default when absent.
    Default(String),
    /// `Option<T>`, absent when `None`.
    Optional,
    /// `Vec<T>`, absent when empty.
    OptionalList,
}

fn plan(namespace: &Namespace, options: &RustOptions) -> Vec<Struct> {
    let mut structs = Vec::new();
    for entity in namespace.entities.values() {
        structs.push(instance_struct(entity, options));
        if let Some(type_struct) = type_struct(entity, options) {
            structs.push(type_struct);
        }
    }
    for property_set in namespace.property_sets.values() {
        structs.push(property_set_struct(property_set, options));
    }
    structs
}

fn instance_struct(entity: &Entity, options: &RustOptions) -> Struct {
    let mut doc = doc_lines(entity.doc.as_deref(), || format!("A `{}`.", entity.name));
    if let Some(version) = entity.deprecated {
        doc.extend([String::new(), deprecation(version)]);
    }
    let mut fields = Vec::new();
    for attribute in &entity.attributes {
        match attribute.placement {
            Placement::Instance => fields.push(attribute_field(attribute, options)),
            Placement::TypeOverridable => fields.push(override_field(attribute, options)),
            Placement::Type => {}
        }
    }
    fields.extend(entity.roles.iter().map(|role| role_field(role, options)));
    Struct {
        name: entity.name.clone(),
        doc,
        fields,
    }
}

fn type_struct(entity: &Entity, options: &RustOptions) -> Option<Struct> {
    let type_def = entity.type_def.as_ref()?;
    let mut doc = doc_lines(type_def.doc.as_deref(), || {
        format!("The type of [`{}`] objects.", entity.name)
    });
    if let Some(version) = entity.deprecated {
        doc.extend([String::new(), deprecation(version)]);
    }
    let fields = entity
        .attributes
        .iter()
        .filter(|attribute| attribute.placement != Placement::Instance)
        .map(|attribute| attribute_field(attribute, options))
        .collect();
    Some(Struct {
        name: type_def.name.clone(),
        doc,
        fields,
    })
}

fn property_set_struct(property_set: &PropertySet, options: &RustOptions) -> Struct {
    let applies_to: Vec<String> = property_set
        .applies_to
        .iter()
        .map(|name| format!("[`{name}`]"))
        .collect();
    Struct {
        name: pascal_case(&property_set.name),
        doc: vec![
            format!("The `{}` property set.", property_set.name),
            String::new(),
            format!("Applies to {}.", applies_to.join(", ")),
        ],
        fields: property_set
            .properties
            .iter()
            .map(|property| Field {
                name: snake_case(&property.name),
                ..attribute_field(property, options)
            })
            .collect(),
    }
}

fn attribute_field(attribute: &Attribute, options: &RustOptions) -> Field {
    let ty = rust_type(&attribute.value, options);
    let kind = match &attribute.presence {
        Presence::Required => FieldKind::Required,
        Presence::Default(value) => FieldKind::Default(literal(value)),
        Presence::Optional if matches!(attribute.value, ValueType::List(_)) => {
            FieldKind::OptionalList
        }
        Presence::Optional => FieldKind::Optional,
    };
    let ty = match kind {
        FieldKind::Optional => format!("Option<{ty}>"),
        _ => ty,
    };
    Field {
        schema_name: attribute.name.clone(),
        name: attribute.name.clone(),
        doc: attribute_doc(attribute),
        ty,
        kind,
    }
}

/// The instance-side field of a `type_overridable` attribute: absent means "use the type's".
fn override_field(attribute: &Attribute, options: &RustOptions) -> Field {
    let mut doc = vec!["Overrides the type's value for this object when set.".to_owned()];
    doc.push(String::new());
    doc.extend(attribute_doc(attribute));
    Field {
        schema_name: attribute.name.clone(),
        name: attribute.name.clone(),
        doc,
        ty: format!("Option<{}>", rust_type(&attribute.value, options)),
        kind: FieldKind::Optional,
    }
}

fn role_field(role: &Role, options: &RustOptions) -> Field {
    let (ty, kind, doc) = match role.cardinality {
        Cardinality::One => (
            options.id_type.clone(),
            FieldKind::Required,
            format!("The object playing the `{}` role.", role.name),
        ),
        Cardinality::Many => (
            format!("Vec<{}>", options.id_type),
            FieldKind::Required,
            format!("The objects playing the `{}` role.", role.name),
        ),
    };
    Field {
        schema_name: role.name.clone(),
        name: role.name.clone(),
        doc: vec![doc],
        ty,
        kind,
    }
}

fn attribute_doc(attribute: &Attribute) -> Vec<String> {
    let mut doc = doc_lines(attribute.doc.as_deref(), || {
        format!("The `{}` value.", attribute.name)
    });
    if let Some(kind) = quantity_of(&attribute.value) {
        doc.extend([String::new(), format!("In {}.", kind.si_unit())]);
    }
    doc
}

fn quantity_of(value: &ValueType) -> Option<schema::QuantityKind> {
    match value {
        ValueType::Quantity(kind) => Some(*kind),
        ValueType::List(inner) => quantity_of(inner),
        _ => None,
    }
}

fn deprecation(version: u32) -> String {
    format!("Deprecated since schema version {version}.")
}

fn doc_lines(doc: Option<&str>, fallback: impl FnOnce() -> String) -> Vec<String> {
    match doc.map(str::trim).filter(|doc| !doc.is_empty()) {
        Some(doc) => doc.lines().map(|line| line.trim_end().to_owned()).collect(),
        None => vec![fallback()],
    }
}

fn rust_type(value: &ValueType, options: &RustOptions) -> String {
    match value {
        ValueType::Bool => "bool".into(),
        ValueType::Integer => "i64".into(),
        ValueType::Real | ValueType::Quantity(_) => "f64".into(),
        ValueType::Text => "String".into(),
        ValueType::Ref(_) => options.id_type.clone(),
        // Rejected by validation for now; an enumeration will become a Rust enum of its name.
        ValueType::Enum(name) => name.clone(),
        ValueType::List(inner) => format!("Vec<{}>", rust_type(inner, options)),
    }
}

/// A Rust expression for a validated default value.
fn literal(value: &Value) -> String {
    match value {
        Value::Bool(value) => value.to_string(),
        Value::Integer(value) => group_digits(&value.to_string()),
        Value::Real(value) => group_digits(&format!("{value:?}")),
        Value::Text(text) => format!("String::from({text:?})"),
        Value::List(items) if items.is_empty() => "Vec::new()".into(),
        Value::List(items) => {
            let items: Vec<String> = items.iter().map(literal).collect();
            format!("vec![{}]", items.join(", "))
        }
    }
}

/// Groups the digits of a number literal by three, as `clippy::unreadable_literal` asks for
/// numbers longer than five digits: `1234567.25` becomes `1_234_567.25`.
fn group_digits(number: &str) -> String {
    let (mantissa, exponent) = number
        .find('e')
        .map_or((number, ""), |index| number.split_at(index));
    let (sign, mantissa) = mantissa
        .strip_prefix('-')
        .map_or(("", mantissa), |rest| ("-", rest));
    let (whole, fraction) = mantissa
        .split_once('.')
        .map_or((mantissa, None), |(whole, fraction)| {
            (whole, Some(fraction))
        });
    let mut out = String::from(sign);
    out.push_str(&group(whole, true));
    if let Some(fraction) = fraction {
        out.push('.');
        out.push_str(&group(fraction, false));
    }
    out.push_str(exponent);
    out
}

/// Inserts `_` every three digits, from the right for whole parts and from the left for
/// fractions, when the run is longer than five digits.
fn group(digits: &str, from_right: bool) -> String {
    if digits.len() <= 5 {
        return digits.to_owned();
    }
    let chars: Vec<char> = digits.chars().collect();
    let offset = if from_right { chars.len() % 3 } else { 0 };
    let mut out = String::new();
    for (index, digit) in chars.iter().enumerate() {
        if index > 0 && (index + 3 - offset) % 3 == 0 {
            out.push('_');
        }
        out.push(*digit);
    }
    out
}

/// `Pset_WallCommon` becomes `PsetWallCommon`.
fn pascal_case(name: &str) -> String {
    name.split('_')
        .flat_map(|word| {
            let mut chars = word.chars();
            chars
                .next()
                .map(|first| first.to_ascii_uppercase())
                .into_iter()
                .chain(chars)
        })
        .collect()
}

/// `IsExternal` becomes `is_external`, `UValue` becomes `u_value`, `HTTPProxy` `http_proxy`.
fn snake_case(name: &str) -> String {
    let chars: Vec<char> = name.chars().collect();
    let mut out = String::new();
    for (index, &c) in chars.iter().enumerate() {
        if c.is_ascii_uppercase() && index > 0 {
            let previous = chars[index - 1];
            let next_is_lower = chars.get(index + 1).is_some_and(char::is_ascii_lowercase);
            if previous.is_ascii_lowercase()
                || previous.is_ascii_digit()
                || (previous.is_ascii_uppercase() && next_is_lower)
            {
                out.push('_');
            }
        }
        out.push(c.to_ascii_lowercase());
    }
    out
}

/// Struct names must be distinct, and field names distinct and usable as identifiers.
fn check_names(structs: &[Struct]) -> Result<(), Vec<Error>> {
    let mut errors = Vec::new();
    let mut struct_names = BTreeSet::new();
    for item in structs {
        if !struct_names.insert(item.name.as_str()) {
            errors.push(format!("two generated structs are named `{}`", item.name));
        }
        let mut field_names = BTreeSet::new();
        for field in &item.fields {
            if NOT_RAW.contains(&field.name.as_str()) {
                errors.push(format!(
                    "`{}` in `{}` cannot be a Rust field name",
                    field.schema_name, item.name
                ));
            } else if !field_names.insert(field.name.as_str()) {
                errors.push(format!(
                    "`{}` in `{}` gives the same Rust field name as another one",
                    field.schema_name, item.name
                ));
            }
        }
    }
    if errors.is_empty() {
        Ok(())
    } else {
        Err(errors
            .into_iter()
            .map(|message| Error::new(ErrorKind::Rust(message)))
            .collect())
    }
}

fn identifier(name: &str) -> String {
    if is_keyword(name) {
        format!("r#{name}")
    } else {
        name.to_owned()
    }
}

/// Strict and reserved keywords of the 2024 edition, which need `r#` as identifiers.
fn is_keyword(name: &str) -> bool {
    const KEYWORDS: [&str; 48] = [
        "abstract", "as", "async", "await", "become", "box", "break", "const", "continue", "do",
        "dyn", "else", "enum", "extern", "false", "final", "fn", "for", "gen", "if", "impl", "in",
        "let", "loop", "macro", "match", "mod", "move", "mut", "override", "priv", "pub", "ref",
        "return", "static", "struct", "trait", "true", "try", "type", "typeof", "unsafe",
        "unsized", "use", "virtual", "where", "while", "yield",
    ];
    KEYWORDS.contains(&name)
}

fn write_doc(out: &mut String, indent: &str, doc: &[String]) {
    for line in doc {
        if line.is_empty() {
            let _ = writeln!(out, "{indent}///");
        } else {
            let _ = writeln!(out, "{indent}/// {line}");
        }
    }
}

fn write_struct(out: &mut String, item: &Struct) {
    write_doc(out, "", &item.doc);
    out.push_str("#[derive(Clone, Debug, PartialEq, serde::Serialize, serde::Deserialize)]\n");
    out.push_str("#[serde(deny_unknown_fields)]\n");
    out.push_str(ALLOWED_LINTS);
    out.push('\n');
    if item.fields.is_empty() {
        let _ = writeln!(out, "pub struct {} {{}}", item.name);
        return;
    }
    let _ = writeln!(out, "pub struct {} {{", item.name);
    for field in &item.fields {
        write_doc(out, "    ", &field.doc);
        if field.schema_name != field.name {
            let _ = writeln!(out, "    #[serde(rename = \"{}\")]", field.schema_name);
        }
        match &field.kind {
            FieldKind::Required => {}
            FieldKind::Default(_) => {
                let _ = writeln!(
                    out,
                    "    #[serde(default = \"{}::default_{}\")]",
                    item.name, field.name
                );
            }
            FieldKind::Optional => {
                out.push_str("    #[serde(default, skip_serializing_if = \"Option::is_none\")]\n");
            }
            FieldKind::OptionalList => {
                out.push_str("    #[serde(default, skip_serializing_if = \"Vec::is_empty\")]\n");
            }
        }
        let _ = writeln!(out, "    pub {}: {},", identifier(&field.name), field.ty);
    }
    out.push_str("}\n");
    write_defaults(out, item);
}

fn write_defaults(out: &mut String, item: &Struct) {
    let defaults: Vec<(&Field, &String)> = item
        .fields
        .iter()
        .filter_map(|field| match &field.kind {
            FieldKind::Default(value) => Some((field, value)),
            _ => None,
        })
        .collect();
    if defaults.is_empty() {
        return;
    }
    let _ = writeln!(out, "\nimpl {} {{", item.name);
    for (index, (field, value)) in defaults.into_iter().enumerate() {
        if index > 0 {
            out.push('\n');
        }
        let _ = writeln!(out, "    fn default_{}() -> {} {{", field.name, field.ty);
        let _ = writeln!(out, "        {value}");
        out.push_str("    }\n");
    }
    out.push_str("}\n");
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn groups_long_numbers() {
        assert_eq!(group_digits("12345"), "12345");
        assert_eq!(group_digits("123456"), "123_456");
        assert_eq!(group_digits("1234567"), "1_234_567");
        assert_eq!(group_digits("-1234567.123456"), "-1_234_567.123_456");
        assert_eq!(group_digits("1.2345678e-7"), "1.234_567_8e-7");
        assert_eq!(group_digits("2.5"), "2.5");
        assert_eq!(group_digits("1e20"), "1e20");
    }

    #[test]
    fn converts_names() {
        assert_eq!(pascal_case("Pset_WallCommon"), "PsetWallCommon");
        assert_eq!(pascal_case("Qto_wallBase"), "QtoWallBase");
        assert_eq!(snake_case("IsExternal"), "is_external");
        assert_eq!(snake_case("UValue"), "u_value");
        assert_eq!(snake_case("HTTPProxy"), "http_proxy");
        assert_eq!(snake_case("Level2Height"), "level2_height");
        assert_eq!(snake_case("ABC"), "abc");
    }

    #[test]
    fn escapes_keywords() {
        assert_eq!(identifier("type"), "r#type");
        assert_eq!(identifier("gen"), "r#gen");
        assert_eq!(identifier("union"), "union");
        assert_eq!(identifier("height"), "height");
    }

    #[test]
    fn writes_literals() {
        assert_eq!(literal(&Value::Bool(true)), "true");
        assert_eq!(literal(&Value::Real(0.0)), "0.0");
        assert_eq!(literal(&Value::Real(1e-7)), "1e-7");
        assert_eq!(literal(&Value::Integer(-1_000_000)), "-1_000_000");
        assert_eq!(literal(&Value::List(Vec::new())), "Vec::new()");
        assert_eq!(
            literal(&Value::List(vec![Value::Text("a\"b".into())])),
            "vec![String::from(\"a\\\"b\")]"
        );
    }
}
