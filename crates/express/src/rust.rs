//! Rust emitter: one type per declared type and entity of a resolved [`Model`], with decoders
//! from STEP parameters, and tests that decode a sample of every one of them.
//!
//! The emitted code calls a small runtime, named by [`RustOptions::runtime`], for everything that
//! does not depend on the schema (see `interop_ifc::ifc::decode`). It is valid Rust but not
//! formatted: it is compiled from `OUT_DIR`, and the sample snapshot is run through rustfmt.

use std::collections::BTreeSet;
use std::fmt::Write as _;

use rust_names::{NOT_RAW, identifier, pascal_case as type_ident, snake_case};

use crate::error::{Error, ErrorKind};
use crate::model::{Aggregate, AttrType, Entity, Model, NameKind, TypeDef, TypeKind};

/// Choices the emitted code depends on.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct RustOptions {
    /// Path of the runtime module the code decodes with, such as `crate::ifc::decode`.
    pub runtime: String,
    /// Documentation page of each declaration, with `{name}` standing for its name, such as
    /// `https://example.org/lexical/{name}.htm`.
    pub doc_url: Option<String>,
}

/// Names the emitted code uses unqualified, which a generated type would shadow.
const USED_NAMES: [&str; 20] = [
    "Box", "DECODERS", "Decoder", "Entity", "Err", "None", "Ok", "Option", "Result", "Self",
    "Some", "String", "Vec", "bool", "f64", "i64", "rt", "str", "u64", "usize",
];

/// Nesting beyond which a sample value is given up on, for types that only contain themselves
/// through aggregates that cannot be empty.
const MAX_SAMPLE_DEPTH: usize = 32;

/// Emits the Rust types of a resolved schema.
///
/// Types and entities come in name order and attributes in STEP order, so the same model always
/// gives the same code.
///
/// # Errors
///
/// Returns an error for each name that cannot become a distinct Rust identifier, enumeration
/// without items, and type with no finite sample value.
pub fn emit_rust(model: &Model, options: &RustOptions) -> Result<String, Vec<Error>> {
    let emitter = Emitter { model, options };
    emitter.check_names()?;
    let mut out = format!(
        "// @generated by express from the `{}` schema. Do not edit.\n\nuse {} as rt;\n",
        model.name, options.runtime
    );
    for def in model.types.values() {
        out.push('\n');
        match &def.kind {
            TypeKind::Defined(underlying) => emitter.defined(&mut out, def, underlying),
            TypeKind::Enumeration(items) => emitter.enumeration(&mut out, def, items),
            TypeKind::Select(_) => emitter.select(&mut out, def),
        }
    }
    for entity in model.entities.values() {
        out.push('\n');
        if entity.is_abstract {
            emitter.marker(&mut out, entity);
        } else {
            emitter.entity(&mut out, entity);
        }
    }
    out.push('\n');
    emitter.entity_enum(&mut out);
    out.push('\n');
    emitter.tests(&mut out).map_err(|error| vec![error])?;
    Ok(out)
}

struct Emitter<'a> {
    model: &'a Model,
    options: &'a RustOptions,
}

/// A variant of a select's enum.
enum Variant {
    /// A defined type or enumeration the select can hold, by declared name.
    Member(String),
    /// `Instance`: an instance of any of the entities the select can hold.
    Instance,
}

impl Variant {
    fn ident(&self) -> String {
        match self {
            Self::Member(member) => type_ident(member),
            Self::Instance => "Instance".to_owned(),
        }
    }
}

impl Emitter<'_> {
    fn instantiable(&self) -> impl Iterator<Item = &Entity> {
        self.model
            .entities
            .values()
            .filter(|entity| !entity.is_abstract)
    }

    /// Types, fields and variants must get distinct, usable Rust names.
    fn check_names(&self) -> Result<(), Vec<Error>> {
        let mut problems = Vec::new();
        let mut type_names = BTreeSet::new();
        let declared = self
            .model
            .types
            .values()
            .map(|def| def.name.as_str())
            .chain(
                self.model
                    .entities
                    .values()
                    .map(|entity| entity.name.as_str()),
            );
        for name in declared {
            let ident = type_ident(name);
            if USED_NAMES.contains(&ident.as_str()) || NOT_RAW.contains(&ident.as_str()) {
                problems.push(format!("`{name}` cannot be a generated type name"));
            } else if !type_names.insert(ident.clone()) {
                problems.push(format!("two generated types are named `{ident}`"));
            }
        }
        for def in self.model.types.values() {
            let variants: Vec<(String, String)> = match &def.kind {
                TypeKind::Defined(_) => continue,
                TypeKind::Enumeration(items) if items.is_empty() => {
                    problems.push(format!("enumeration `{}` has no items", def.name));
                    continue;
                }
                TypeKind::Enumeration(items) => items
                    .iter()
                    .map(|item| (item.clone(), variant_ident(item)))
                    .collect(),
                TypeKind::Select(_) => {
                    let variants = self.select_variants(def);
                    if variants.is_empty() {
                        problems.push(format!("select `{}` has no members", def.name));
                        continue;
                    }
                    variants
                        .iter()
                        .map(|variant| match variant {
                            Variant::Member(member) => (member.clone(), variant.ident()),
                            Variant::Instance => ("an entity".to_owned(), variant.ident()),
                        })
                        .collect()
                }
            };
            let mut seen = BTreeSet::new();
            for (item, ident) in variants {
                if NOT_RAW.contains(&ident.as_str()) || !seen.insert(ident.clone()) {
                    problems.push(format!(
                        "`{item}` in `{}` cannot become a distinct Rust variant",
                        def.name
                    ));
                }
            }
        }
        for entity in self.instantiable() {
            let mut seen = BTreeSet::new();
            for attribute in entity
                .attributes
                .iter()
                .filter(|attribute| !attribute.derived)
            {
                let ident = snake_case(&attribute.name);
                if NOT_RAW.contains(&ident.as_str()) || !seen.insert(ident) {
                    problems.push(format!(
                        "`{}` in `{}` cannot become a distinct Rust field",
                        attribute.name, entity.name
                    ));
                }
            }
        }
        if problems.is_empty() {
            Ok(())
        } else {
            Err(problems
                .into_iter()
                .map(|problem| Error::new(ErrorKind::Rust(problem)))
                .collect())
        }
    }

    /// The variants of a select: one per defined type or enumeration it can hold, in name
    /// order, then `Instance` when it can hold entities.
    fn select_variants(&self, def: &TypeDef) -> Vec<Variant> {
        let (entities, members): (Vec<String>, Vec<String>) = self
            .model
            .select_members(&def.name)
            .into_iter()
            .partition(|member| self.model.kind_of(member) == Some(NameKind::Entity));
        let mut variants: Vec<Variant> = members.into_iter().map(Variant::Member).collect();
        if !entities.is_empty() {
            variants.push(Variant::Instance);
        }
        variants
    }

    fn doc(&self, out: &mut String, summary: &str, name: &str) {
        let _ = writeln!(out, "/// {summary}");
        if let Some(url) = &self.options.doc_url {
            out.push_str("///\n");
            let _ = writeln!(out, "/// See <{}>.", url.replace("{name}", name));
        }
    }

    fn rust_type(&self, ty: &AttrType) -> String {
        match ty {
            AttrType::Binary => "rt::Binary".into(),
            AttrType::Boolean => "bool".into(),
            AttrType::Integer => "i64".into(),
            AttrType::Logical => "rt::Logical".into(),
            AttrType::Number => "rt::Number".into(),
            AttrType::Real => "f64".into(),
            AttrType::String => "String".into(),
            AttrType::Named(name) if self.model.kind_of(name) == Some(NameKind::Entity) => {
                format!("rt::Ref<{}>", type_ident(name))
            }
            AttrType::Named(name) => type_ident(name),
            AttrType::Aggregate(aggregate) => {
                let element = self.rust_type(&aggregate.element);
                if aggregate.optional_elements {
                    format!("Vec<Option<{element}>>")
                } else {
                    format!("Vec<{element}>")
                }
            }
        }
    }

    fn defined(&self, out: &mut String, def: &TypeDef, underlying: &AttrType) {
        let ident = type_ident(&def.name);
        self.doc(out, &format!("The `{}` defined type.", def.name), &def.name);
        out.push_str("#[derive(Clone, Debug, PartialEq)]\n");
        let _ = writeln!(
            out,
            "pub struct {ident}(pub {});",
            self.rust_type(underlying)
        );
        let _ = write!(
            out,
            "\nimpl rt::Decode for {ident} {{\n    \
             fn decode(parameter: &rt::Parameter) -> Result<Self, rt::ValueError> {{\n        \
             {}(parameter).map(Self)\n    }}\n}}\n",
            decoder(underlying)
        );
    }

    fn enumeration(&self, out: &mut String, def: &TypeDef, items: &[String]) {
        let ident = type_ident(&def.name);
        self.doc(out, &format!("The `{}` enumeration.", def.name), &def.name);
        out.push_str("#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]\n");
        let _ = writeln!(out, "pub enum {ident} {{");
        for item in items {
            let _ = writeln!(out, "    /// `.{}.`", item.to_ascii_uppercase());
            let _ = writeln!(out, "    {},", variant_ident(item));
        }
        out.push_str("}\n");
        let _ = writeln!(out, "\nimpl {ident} {{");
        out.push_str("    /// Every item, with its STEP spelling.\n");
        out.push_str("    pub const ITEMS: &'static [(&'static str, Self)] = &[\n");
        for item in items {
            let _ = writeln!(
                out,
                "        (\"{}\", Self::{}),",
                item.to_ascii_uppercase(),
                variant_ident(item)
            );
        }
        out.push_str("    ];\n}\n");
        let _ = write!(
            out,
            "\nimpl rt::Decode for {ident} {{\n    \
             fn decode(parameter: &rt::Parameter) -> Result<Self, rt::ValueError> {{\n        \
             rt::enumeration(parameter, Self::ITEMS)\n    }}\n}}\n"
        );
    }

    fn select(&self, out: &mut String, def: &TypeDef) {
        let ident = type_ident(&def.name);
        let variants = self.select_variants(def);
        self.doc(out, &format!("The `{}` select type.", def.name), &def.name);
        out.push_str("#[derive(Clone, Debug, PartialEq)]\n");
        let _ = writeln!(out, "pub enum {ident} {{");
        for variant in &variants {
            let name = variant.ident();
            match variant {
                Variant::Member(member) => {
                    let _ = writeln!(out, "    /// A `{member}` value.\n    {name}({name}),");
                }
                Variant::Instance => out.push_str(
                    "    /// An instance of one of the entities of the select.\n    Instance(u64),\n",
                ),
            }
        }
        out.push_str("}\n");
        let _ = write!(
            out,
            "\nimpl rt::Decode for {ident} {{\n    \
             fn decode(parameter: &rt::Parameter) -> Result<Self, rt::ValueError> {{\n        \
             match rt::select(parameter)? {{\n"
        );
        for variant in &variants {
            if let Variant::Member(member) = variant {
                let _ = writeln!(
                    out,
                    "            rt::Selected::Typed(\"{}\", value) => rt::decode(value).map(Self::{}),",
                    member.to_ascii_uppercase(),
                    variant.ident()
                );
            }
        }
        // Values the select cannot hold: typed values of other types, and references when it
        // holds no entities.
        let other = if variants
            .iter()
            .any(|variant| matches!(variant, Variant::Instance))
        {
            out.push_str("            rt::Selected::Instance(id) => Ok(Self::Instance(id)),\n");
            "rt::Selected::Typed(..)"
        } else {
            "rt::Selected::Instance(_) | rt::Selected::Typed(..)"
        };
        let _ = writeln!(
            out,
            "            {other} => Err(rt::ValueError::NotInSelect),"
        );
        out.push_str("        }\n    }\n}\n");
    }

    /// An abstract entity: a type to refer to, with no values.
    fn marker(&self, out: &mut String, entity: &Entity) {
        self.doc(
            out,
            &format!(
                "The abstract `{}` entity, which references can point to through its subtypes.",
                entity.name
            ),
            &entity.name,
        );
        out.push_str("#[derive(Debug)]\n");
        let _ = writeln!(out, "pub struct {}(());", type_ident(&entity.name));
    }

    fn entity(&self, out: &mut String, entity: &Entity) {
        let ident = type_ident(&entity.name);
        self.doc(out, &format!("The `{}` entity.", entity.name), &entity.name);
        out.push_str("#[derive(Clone, Debug, PartialEq)]\n");
        let fields: Vec<_> = entity
            .attributes
            .iter()
            .filter(|attribute| !attribute.derived)
            .collect();
        if fields.is_empty() {
            let _ = writeln!(out, "pub struct {ident} {{}}");
        } else {
            let _ = writeln!(out, "pub struct {ident} {{");
            for attribute in &fields {
                if attribute.declared_by == entity.name {
                    let _ = writeln!(out, "    /// `{}`.", attribute.name);
                } else {
                    let _ = writeln!(
                        out,
                        "    /// `{}`, inherited from `{}`.",
                        attribute.name, attribute.declared_by
                    );
                }
                let ty = self.rust_type(&attribute.ty);
                let ty = if attribute.optional {
                    format!("Option<{ty}>")
                } else {
                    ty
                };
                let _ = writeln!(out, "    pub {}: {ty},", field_ident(&attribute.name));
            }
            out.push_str("}\n");
        }
        let derived: Vec<String> = entity
            .attributes
            .iter()
            .enumerate()
            .filter(|(_, attribute)| attribute.derived)
            .map(|(index, _)| index.to_string())
            .collect();
        let _ = write!(
            out,
            "\nimpl {ident} {{\n    \
             /// The entity name as written in STEP files.\n    \
             pub const STEP_NAME: &'static str = \"{}\";\n\n    \
             /// Decodes a record of this entity; its name is not checked.\n    \
             ///\n    \
             /// # Errors\n    \
             ///\n    \
             /// Returns a [`rt::DecodeError`] when the record does not match the entity's attributes.\n    \
             pub fn from_record(record: &rt::Record) -> Result<Self, rt::DecodeError> {{\n",
            entity.name.to_ascii_uppercase()
        );
        let count = entity.attributes.len();
        let derived = derived.join(", ");
        if fields.is_empty() {
            let _ = writeln!(
                out,
                "        rt::Attributes::new(record, {count}, &[{derived}])?;"
            );
            out.push_str("        Ok(Self {})\n");
        } else {
            let _ = writeln!(
                out,
                "        let mut attributes = rt::Attributes::new(record, {count}, &[{derived}])?;"
            );
            out.push_str("        Ok(Self {\n");
            for attribute in &fields {
                let read = if attribute.optional {
                    "optional"
                } else {
                    "required"
                };
                let _ = writeln!(
                    out,
                    "            {}: attributes.{read}({})?,",
                    field_ident(&attribute.name),
                    decoder(&attribute.ty)
                );
            }
            out.push_str("        })\n");
        }
        out.push_str("    }\n}\n");
    }

    /// `Entity`, with one variant per entity that can be instantiated, and its decoders.
    fn entity_enum(&self, out: &mut String) {
        out.push_str(
            "/// An instance of any entity of the schema that can be instantiated.\n\
             #[derive(Clone, Debug, PartialEq)]\n\
             pub enum Entity {\n",
        );
        for entity in self.instantiable() {
            let ident = type_ident(&entity.name);
            let _ = writeln!(out, "    /// An [`{ident}`].");
            let _ = writeln!(out, "    {ident}(Box<{ident}>),");
        }
        out.push_str(
            "}\n\n\
             impl Entity {\n    \
             /// Decodes a record of any entity of the schema that can be instantiated.\n    \
             ///\n    \
             /// # Errors\n    \
             ///\n    \
             /// Returns a [`rt::DecodeError`] when the record names no such entity or does not match\n    \
             /// its attributes.\n    \
             pub fn from_record(record: &rt::Record) -> Result<Self, rt::DecodeError> {\n        \
             let index = DECODERS\n            \
             .binary_search_by(|(name, _)| (*name).cmp(record.name.as_str()))\n            \
             .map_err(|_| rt::DecodeError::UnknownEntity)?;\n        \
             (DECODERS[index].1)(record)\n    \
             }\n\n    \
             /// Decodes an instance of the data section.\n    \
             ///\n    \
             /// # Errors\n    \
             ///\n    \
             /// Returns a [`rt::DecodeError`] for complex instances, and as [`Self::from_record`] does.\n    \
             pub fn from_instance(body: &rt::InstanceBody) -> Result<Self, rt::DecodeError> {\n        \
             match body {\n            \
             rt::InstanceBody::Simple(record) => Self::from_record(record),\n            \
             rt::InstanceBody::Complex(_) => Err(rt::DecodeError::ComplexInstance),\n        \
             }\n    \
             }\n\n    \
             /// The entity name as written in STEP files.\n    \
             #[must_use]\n    \
             pub fn step_name(&self) -> &'static str {\n        \
             match self {\n",
        );
        for entity in self.instantiable() {
            let ident = type_ident(&entity.name);
            let _ = writeln!(out, "            Self::{ident}(_) => {ident}::STEP_NAME,");
        }
        out.push_str(
            "        }\n    }\n}\n\n\
             /// Decoders of every entity that can be instantiated, sorted by STEP name.\n\
             type Decoder = fn(&rt::Record) -> Result<Entity, rt::DecodeError>;\n\n\
             const DECODERS: &[(&str, Decoder)] = &[\n",
        );
        let mut decoders: Vec<(String, String)> = self
            .instantiable()
            .map(|entity| (entity.name.to_ascii_uppercase(), type_ident(&entity.name)))
            .collect();
        decoders.sort();
        for (step_name, ident) in decoders {
            let _ = writeln!(
                out,
                "    (\"{step_name}\", |record| {ident}::from_record(record).map(Box::new).map(Entity::{ident})),"
            );
        }
        out.push_str("];\n");
    }

    /// Tests that decode a sample of every entity, defined type, select member and enumeration
    /// item, so the generated code is exercised in full.
    fn tests(&self, out: &mut String) -> Result<(), Error> {
        let entity_samples = self.entity_samples()?;
        let count = self.instantiable().count();
        let (samples, checks) = self.type_samples()?;
        let mut type_samples = String::new();
        for (index, sample) in samples.iter().enumerate() {
            let _ = writeln!(type_samples, "#{}=V({sample});", index + 1);
        }
        out.push_str("#[cfg(test)]\nmod tests {\n    use super::*;\n\n");
        let _ = writeln!(
            out,
            "    const ENTITY_SAMPLES: &str = {};\n",
            raw_string(&entity_samples)
        );
        let _ = writeln!(
            out,
            "    const TYPE_SAMPLES: &str = {};\n",
            raw_string(&type_samples)
        );
        out.push_str(
            "    fn records(data: &str) -> Vec<rt::Record> {\n        \
             let file = format!(\"ISO-10303-21;\\nHEADER;\\nENDSEC;\\nDATA;\\n{data}ENDSEC;\\nEND-ISO-10303-21;\\n\");\n        \
             rt::StepReader::new(file.as_bytes(), rt::Limits::default())\n            \
             .unwrap()\n            \
             .map(|instance| {\n                \
             let rt::InstanceBody::Simple(record) = instance.unwrap().body else {\n                    \
             panic!(\"samples are simple instances\");\n                \
             };\n                \
             record\n            \
             })\n            \
             .collect()\n    \
             }\n\n    \
             fn check_items<T: rt::Decode + Copy + PartialEq + std::fmt::Debug>(items: &[(&str, T)]) {\n        \
             for &(name, item) in items {\n            \
             let value = rt::Parameter::Enumeration(name.to_owned());\n            \
             assert_eq!(rt::decode(&value), Ok(item));\n        \
             }\n    \
             }\n\n    \
             #[test]\n    \
             fn every_entity_decodes_from_a_sample() {\n        \
             let records = records(ENTITY_SAMPLES);\n",
        );
        let _ = writeln!(out, "        assert_eq!(records.len(), {count});");
        out.push_str(
            "        for record in &records {\n            \
             let entity = Entity::from_record(record).unwrap();\n            \
             assert_eq!(entity.step_name(), record.name);\n            \
             let body = rt::InstanceBody::Simple(record.clone());\n            \
             assert_eq!(Entity::from_instance(&body), Ok(entity));\n        \
             }\n    \
             }\n\n    \
             #[test]\n    \
             fn rejects_unknown_and_complex_instances() {\n        \
             let record = rt::Record {\n            \
             name: \"NOT AN ENTITY\".to_owned(),\n            \
             parameters: Vec::new(),\n        \
             };\n        \
             assert_eq!(\n            \
             Entity::from_record(&record),\n            \
             Err(rt::DecodeError::UnknownEntity)\n        \
             );\n        \
             let body = rt::InstanceBody::Complex(vec![record]);\n        \
             assert_eq!(\n            \
             Entity::from_instance(&body),\n            \
             Err(rt::DecodeError::ComplexInstance)\n        \
             );\n    \
             }\n\n    \
             #[test]\n    \
             fn every_type_decodes_from_a_sample() {\n        \
             let records = records(TYPE_SAMPLES);\n        \
             let mut values = records.iter().map(|record| &record.parameters[0]);\n        \
             let mut next = || values.next().unwrap();\n",
        );
        for check in checks {
            let _ = writeln!(out, "        {check}");
        }
        out.push_str("        assert!(values.next().is_none());\n    }\n}\n");
        Ok(())
    }

    /// One record per entity that can be instantiated, with a value for every attribute.
    fn entity_samples(&self) -> Result<String, Error> {
        let mut samples = String::new();
        for (index, entity) in self.instantiable().enumerate() {
            let mut parameters = Vec::new();
            for attribute in &entity.attributes {
                if attribute.derived {
                    parameters.push("*".to_owned());
                } else {
                    parameters.push(self.sample(&attribute.ty, 0)?);
                }
            }
            let _ = writeln!(
                samples,
                "#{}={}({});",
                index + 1,
                entity.name.to_ascii_uppercase(),
                parameters.join(",")
            );
        }
        Ok(samples)
    }

    /// A sample value of every defined type and select member, with the check of each, plus a
    /// check of every enumeration's items.
    fn type_samples(&self) -> Result<(Vec<String>, Vec<String>), Error> {
        let mut samples = Vec::new();
        let mut checks = Vec::new();
        for def in self.model.types.values() {
            let ident = type_ident(&def.name);
            match &def.kind {
                TypeKind::Defined(underlying) => {
                    samples.push(self.sample(underlying, 0)?);
                    checks.push(format!("assert!(rt::decode::<{ident}>(next()).is_ok());"));
                }
                TypeKind::Enumeration(_) => checks.push(format!("check_items({ident}::ITEMS);")),
                TypeKind::Select(_) => {
                    for variant in self.select_variants(def) {
                        samples.push(self.variant_sample(&variant, 0)?);
                        let pattern = match variant {
                            Variant::Member(_) => format!("{}(_)", variant.ident()),
                            Variant::Instance => "Instance(1)".to_owned(),
                        };
                        checks.push(format!(
                            "assert!(matches!(rt::decode::<{ident}>(next()), Ok({ident}::{pattern})));"
                        ));
                    }
                }
            }
        }
        Ok((samples, checks))
    }

    /// A STEP value of type `ty`, as it would be written for an attribute.
    fn sample(&self, ty: &AttrType, depth: usize) -> Result<String, Error> {
        if depth > MAX_SAMPLE_DEPTH {
            let message = format!("no finite sample value of `{}`", self.rust_type(ty));
            return Err(Error::new(ErrorKind::Rust(message)));
        }
        let sample = match ty {
            AttrType::Binary => "\"0\"".to_owned(),
            AttrType::Boolean => ".T.".to_owned(),
            AttrType::Integer | AttrType::Number => "1".to_owned(),
            AttrType::Logical => ".U.".to_owned(),
            AttrType::Real => "1.".to_owned(),
            AttrType::String => "'a'".to_owned(),
            AttrType::Aggregate(aggregate) => self.aggregate_sample(aggregate, depth)?,
            AttrType::Named(name) => match self.model.type_def(name) {
                None => "#1".to_owned(),
                Some(def) => match &def.kind {
                    TypeKind::Defined(underlying) => self.sample(underlying, depth + 1)?,
                    TypeKind::Enumeration(items) => format!(".{}.", items[0].to_ascii_uppercase()),
                    TypeKind::Select(_) => {
                        // `check_names` rejects selects without members.
                        let first = self.select_variants(def).swap_remove(0);
                        self.variant_sample(&first, depth + 1)?
                    }
                },
            },
        };
        Ok(sample)
    }

    /// A value of a select variant: a typed value of a member, or a reference.
    fn variant_sample(&self, variant: &Variant, depth: usize) -> Result<String, Error> {
        match variant {
            Variant::Member(member) => {
                let value = self.sample(&AttrType::Named(member.clone()), depth)?;
                Ok(format!("{}({value})", member.to_ascii_uppercase()))
            }
            Variant::Instance => Ok("#1".to_owned()),
        }
    }

    /// One element when the bounds allow it, so element decoders run; more when required.
    fn aggregate_sample(&self, aggregate: &Aggregate, depth: usize) -> Result<String, Error> {
        let count = aggregate
            .min
            .max(1)
            .min(aggregate.max.unwrap_or(usize::MAX));
        let element = self.sample(&aggregate.element, depth + 1)?;
        Ok(format!("({})", vec![element; count].join(",")))
    }
}

/// A raw string literal of `text`, with as few `#` as it needs.
fn raw_string(text: &str) -> String {
    let mut hashes = String::new();
    while text.contains(&format!("\"{hashes}")) {
        hashes.push('#');
    }
    format!("r{hashes}\"{text}\"{hashes}")
}

/// The decoder expression of a value of type `ty`.
fn decoder(ty: &AttrType) -> String {
    match ty {
        AttrType::Aggregate(aggregate) => {
            let element = decoder(&aggregate.element);
            let element = if aggregate.optional_elements {
                format!("rt::nullable({element})")
            } else {
                element
            };
            let max = aggregate
                .max
                .map_or_else(|| "None".to_owned(), |max| format!("Some({max})"));
            format!("rt::aggregate({}, {max}, {element})", aggregate.min)
        }
        _ => "rt::decode".to_owned(),
    }
}

/// `GlobalId` becomes `global_id`, `UDegree` `u_degree`, keywords such as `type` `r#type`.
fn field_ident(name: &str) -> String {
    identifier(&snake_case(name))
}

/// `NOTDEFINED` becomes `Notdefined`, `T_BEAM` `TBeam`.
fn variant_ident(item: &str) -> String {
    type_ident(&item.to_ascii_lowercase())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::{parse, resolve};

    fn emit(body: &str) -> Result<String, Vec<String>> {
        let schema = parse(&format!("SCHEMA s;\n{body}\nEND_SCHEMA;")).unwrap();
        let model = resolve(&schema).unwrap();
        let options = RustOptions {
            runtime: "rt".into(),
            doc_url: None,
        };
        emit_rust(&model, &options)
            .map_err(|errors| errors.iter().map(ToString::to_string).collect::<Vec<_>>())
    }

    #[test]
    fn converts_names() {
        assert_eq!(type_ident("IfcWall"), "IfcWall");
        assert_eq!(type_ident("length_measure"), "LengthMeasure");
        assert_eq!(type_ident("fn"), "Fn");
        assert_eq!(variant_ident("NOTDEFINED"), "Notdefined");
        assert_eq!(variant_ident("T_BEAM"), "TBeam");
        assert_eq!(variant_ident("E_UTRAN_NODE_B"), "EUtranNodeB");
        assert_eq!(field_ident("GlobalId"), "global_id");
        assert_eq!(field_ident("UDegree"), "u_degree");
        assert_eq!(field_ident("Axis2Placement"), "axis2_placement");
        assert_eq!(field_ident("Type"), "r#type");
        assert_eq!(field_ident("HTTPProxy"), "http_proxy");
    }

    #[test]
    fn writes_raw_strings() {
        assert_eq!(raw_string("a"), "r\"a\"");
        assert_eq!(raw_string("\"0\","), "r#\"\"0\",\"#");
        assert_eq!(raw_string("\"#"), "r##\"\"#\"##");
    }

    #[test]
    fn writes_decoders() {
        assert_eq!(decoder(&AttrType::Real), "rt::decode");
        let nested = AttrType::Aggregate(Box::new(Aggregate {
            kind: crate::ast::AggregateKind::List,
            min: 2,
            max: None,
            optional_elements: false,
            unique: false,
            element: AttrType::Aggregate(Box::new(Aggregate {
                kind: crate::ast::AggregateKind::Array,
                min: 3,
                max: Some(3),
                optional_elements: true,
                unique: false,
                element: AttrType::Real,
            })),
        }));
        assert_eq!(
            decoder(&nested),
            "rt::aggregate(2, None, rt::aggregate(3, Some(3), rt::nullable(rt::decode)))"
        );
    }

    #[test]
    fn rejects_names_rust_cannot_use() {
        assert_eq!(
            emit("TYPE Vec = REAL; END_TYPE; TYPE a_b = REAL; END_TYPE; TYPE AB = REAL; END_TYPE;"),
            Err(vec![
                "two generated types are named `AB`".to_owned(),
                "`Vec` cannot be a generated type name".to_owned(),
            ])
        );
        assert_eq!(
            emit("ENTITY Decoder; END_ENTITY;"),
            Err(vec!["`Decoder` cannot be a generated type name".to_owned()])
        );
        assert_eq!(
            emit("TYPE s = SELECT; END_TYPE; ENTITY e; a : s; END_ENTITY;"),
            Err(vec!["select `s` has no members".to_owned()])
        );
        assert_eq!(
            emit(
                "TYPE e = ENUMERATION OF (A_B, A__B); END_TYPE; TYPE f = EXTENSIBLE ENUMERATION; END_TYPE;"
            ),
            Err(vec![
                "`A__B` in `e` cannot become a distinct Rust variant".to_owned(),
                "enumeration `f` has no items".to_owned(),
            ])
        );
        assert_eq!(
            emit(
                "TYPE s = SELECT (Instance, x); END_TYPE; TYPE Instance = REAL; END_TYPE; ENTITY x; END_ENTITY;"
            ),
            Err(vec![
                "`an entity` in `s` cannot become a distinct Rust variant".to_owned()
            ])
        );
        assert_eq!(
            emit("ENTITY a; GlobalId : REAL; Global_Id : REAL; END_ENTITY;"),
            Err(vec![
                "`Global_Id` in `a` cannot become a distinct Rust field".to_owned()
            ])
        );
        assert_eq!(
            emit("ENTITY a; Crate : REAL; END_ENTITY;"),
            Err(vec![
                "`Crate` in `a` cannot become a distinct Rust field".to_owned()
            ])
        );
    }

    #[test]
    fn gives_up_on_types_without_finite_samples() {
        assert_eq!(
            emit("TYPE a = SELECT (l); END_TYPE; TYPE l = LIST [1:?] OF a; END_TYPE;"),
            Err(vec!["no finite sample value of `L`".to_owned()])
        );
    }

    #[test]
    fn same_model_same_code() {
        let body = "TYPE t = REAL; END_TYPE; ENTITY a; x : t; END_ENTITY;";
        assert_eq!(emit(body), emit(body));
    }
}
