"""Generate the PROJ reference values that `crates/georef/tests/proj.rs` checks against (GEOREF-03).

Run from the repository root (needs network access once, to fetch pyproj, which bundles PROJ and
its EPSG database):

    uv run --no-project --python 3.12 --with pyproj==3.7.1 \
        python crates/georef/tests/proj/generate.py > crates/georef/tests/proj/reference.txt

The tests never call PROJ: they read the committed `reference.txt`. Its header records the pyproj,
PROJ and EPSG dataset versions and the command above. Every number is printed with `repr`, the
shortest decimal that reads back to the same double.

Line formats, space separated, angles in degrees, lengths in metres:

    project  <case> <lon> <lat> <easting> <northing> <convergence> <scale>
    geocentric <case> <lon> <lat> <h> <x> <y> <z>
    helmert  <case> <lon> <lat> <h> <lon'> <lat'> <h'>

`project` cases are EPSG codes (`epsg:2154`) or `tmerc_wide`; the input is on the CRS's own
geographic CRS, so no datum shift is involved. `convergence` is PROJ's meridian convergence and
`scale` its point scale factor (`proj_factors`).
"""

import sys

import pyproj
from pyproj import CRS, Proj, Transformer
from pyproj.database import get_database_metadata

COMMAND = (
    "uv run --no-project --python 3.12 --with pyproj==3.7.1 "
    "python crates/georef/tests/proj/generate.py > crates/georef/tests/proj/reference.txt"
)


def steps(lo, hi, count):
    """`count` evenly spaced values from `lo` to `hi`, both included, built from integers."""
    return [lo + (hi - lo) * i / (count - 1) for i in range(count)]


def utm_grid(zone, south):
    """The full zone width (6 degrees, plus half a degree either side), pole to equator."""
    central = -183 + 6 * zone
    lons = steps(central - 3.5, central + 3.5, 15)
    lats = steps(-80.0, 0.0, 11) if south else steps(0.0, 84.0, 13)
    return [(lon, lat) for lat in lats for lon in lons]


def lambert93_grid():
    """Mainland France and Corsica, with a margin."""
    return [(lon, lat) for lat in steps(41.0, 51.5, 15) for lon in steps(-6.0, 10.5, 12)]


def cc_grid(lat0):
    """A conic conformal zone: one degree either side of its origin latitude."""
    return [(lon, lat) for lat in steps(lat0 - 1.0, lat0 + 1.0, 9) for lon in steps(-6.0, 10.5, 12)]


def wide_grid():
    """Transverse Mercator far beyond a UTM zone, where the classic series lose accuracy."""
    return [(lon, lat) for lat in steps(-80.0, 80.0, 9) for lon in steps(-30.0, 36.0, 12)]


def project_cases():
    cases = [("epsg:2154", CRS.from_epsg(2154), lambert93_grid())]
    for code in range(3942, 3951):
        cases.append((f"epsg:{code}", CRS.from_epsg(code), cc_grid(code - 3900)))
    for zone in range(28, 39):
        cases.append((f"epsg:{25800 + zone}", CRS.from_epsg(25800 + zone), utm_grid(zone, False)))
    for zone in (1, 31, 60):
        cases.append((f"epsg:{32600 + zone}", CRS.from_epsg(32600 + zone), utm_grid(zone, False)))
    for zone in (1, 33, 60):
        cases.append((f"epsg:{32700 + zone}", CRS.from_epsg(32700 + zone), utm_grid(zone, True)))
    wide = CRS.from_proj4("+proj=tmerc +lat_0=0 +lon_0=3 +k=0.9996 +x_0=500000 +y_0=0 +ellps=GRS80")
    cases.append(("tmerc_wide", wide, wide_grid()))
    return cases


DEG_TO_RAD = "+step +proj=unitconvert +xy_in=deg +xy_out=rad"
RAD_TO_DEG = "+step +proj=unitconvert +xy_in=rad +xy_out=deg"

# OSGB36 to WGS 84 (EPSG:1314), a seven-parameter transformation with large rotations and scale,
# applied in both conventions so the sign of the rotations is checked.
OSGB36_TO_WGS84 = "+x=446.448 +y=-125.157 +z=542.06 +rx=0.15 +ry=0.247 +rz=0.842 +s=-20.489"


def geocentric_cases():
    points = [
        (lon, lat, h)
        for h in (-100.0, 0.0, 4807.0)
        for lat in steps(-90.0, 90.0, 13)
        for lon in steps(-180.0, 180.0, 9)
    ]
    for ellps in ("GRS80", "WGS84"):
        pipeline = f"+proj=pipeline {DEG_TO_RAD} +step +proj=cart +ellps={ellps}"
        yield f"geocentric {ellps}", Transformer.from_pipeline(pipeline), points


def helmert_cases():
    points = [(lon, lat, h) for h in (0.0, 1000.0) for lat in steps(49.0, 61.0, 7) for lon in steps(-8.0, 2.0, 6)]
    for convention in ("coordinate_frame", "position_vector"):
        pipeline = (
            f"+proj=pipeline {DEG_TO_RAD} +step +proj=cart +ellps=airy "
            f"+step +proj=helmert {OSGB36_TO_WGS84} +convention={convention} "
            f"+step +inv +proj=cart +ellps=WGS84 {RAD_TO_DEG}"
        )
        yield f"helmert {convention}", Transformer.from_pipeline(pipeline), points


def main(out):
    out.write("# PROJ reference values for crates/georef (GEOREF-03). Do not edit.\n")
    out.write(f"# Generated by crates/georef/tests/proj/generate.py with:\n#   {COMMAND}\n")
    out.write(
        f"# pyproj {pyproj.__version__}, PROJ {pyproj.proj_version_str}, "
        f"EPSG dataset {get_database_metadata('EPSG.VERSION')}\n"
    )
    for name, crs, points in project_cases():
        to_projected = Transformer.from_crs(crs.geodetic_crs, crs, always_xy=True)
        factors = Proj(crs)
        for lon, lat in points:
            e, n = to_projected.transform(lon, lat, errcheck=True)
            f = factors.get_factors(lon, lat, errcheck=True)
            values = (lon, lat, e, n, f.meridian_convergence, f.parallel_scale)
            out.write(f"project {name} {' '.join(map(repr, values))}\n")
    for kind_case, transformer, points in (*geocentric_cases(), *helmert_cases()):
        for lon, lat, h in points:
            result = transformer.transform(lon, lat, h, errcheck=True)
            out.write(f"{kind_case} {' '.join(map(repr, (lon, lat, h, *result)))}\n")


if __name__ == "__main__":
    main(sys.stdout)
