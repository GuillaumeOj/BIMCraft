//! JSON Schema emitter (API-02): one definition per entity, per entity type, per property set and
//! per enumeration, describing the JSON the generated Rust types read and write.

use std::collections::BTreeSet;

use schema::{Cardinality, Enumeration, Namespace, Value, ValueType};
use serde_json::{Map, Value as Json, json};

use crate::layout::{self, FieldKind, FieldType};
use crate::{Error, ErrorKind};

/// The JSON Schema draft the emitted documents declare and follow.
pub const DRAFT: &str = "https://json-schema.org/draft/2020-12/schema";

/// The definition object identifiers refer to; no schema record may take its name.
const OBJECT_ID: &str = "ObjectId";
const OBJECT_ID_REF: &str = "#/$defs/ObjectId";
/// The definition of a source (ADR 0018), present when the namespace has sourced values.
const SOURCE: &str = "Source";
const SOURCE_REF: &str = "#/$defs/Source";

/// Choices the emitted schema depends on.
#[derive(Clone, Debug, PartialEq)]
pub struct JsonSchemaOptions {
    /// The `$id` of the document, such as `urn:bimcraft:schema:core`.
    pub id: String,
    /// The JSON Schema of an object identifier, used for `ref:` values and roles; the JSON
    /// counterpart of [`RustOptions::id_type`](crate::RustOptions::id_type).
    pub object_id: Json,
}

/// Emits the JSON Schema of a namespace, as pretty-printed JSON ending with a newline.
///
/// The namespace is validated first. Every record becomes a definition under `$defs`, named as
/// in the schema; objects reject unknown keys, as the Rust types do. The same namespace always
/// gives the same text.
///
/// # Errors
///
/// Returns validation errors, and record names that would make two definitions collide.
pub fn emit_json_schema(
    namespace: &Namespace,
    options: &JsonSchemaOptions,
) -> Result<String, Vec<Error>> {
    let structs = layout::plan(namespace, |name| format!("`{name}`"))?;
    let sourced = structs
        .iter()
        .flat_map(|item| &item.fields)
        .any(|field| matches!(field.ty, FieldType::Sourced(_)));
    check_names(
        structs
            .iter()
            .map(|item| item.name.as_str())
            .chain(namespace.enumerations.keys().map(String::as_str))
            .chain(sourced.then_some(SOURCE)),
    )?;
    let mut defs = Map::new();
    defs.insert(OBJECT_ID.to_owned(), options.object_id.clone());
    if sourced {
        defs.insert(SOURCE.to_owned(), source_definition());
    }
    for item in structs {
        let definition = definition(&item);
        defs.insert(item.name, definition);
    }
    for enumeration in namespace.enumerations.values() {
        defs.insert(
            enumeration.name.clone(),
            enumeration_definition(enumeration),
        );
    }
    let document = json!({
        "$schema": DRAFT,
        "$id": options.id,
        "$comment": "@generated by schema-gen from the schema definitions. Do not edit.",
        "title": format!("BIMCraft `{}` schema", namespace.name),
        "description": format!(
            "Objects of the `{}` schema, version {}.",
            namespace.name, namespace.version
        ),
        "$defs": defs,
    });
    // Serializing a `serde_json::Value` cannot fail: its keys are strings and its numbers finite.
    let mut text = serde_json::to_string_pretty(&document).unwrap_or_default();
    text.push('\n');
    Ok(text)
}

fn definition(item: &layout::Struct) -> Json {
    let mut properties = Map::new();
    let mut required = Vec::new();
    for field in &item.fields {
        let mut property = value_schema(&field.ty);
        if matches!(field.kind, FieldKind::Optional) {
            // The Rust field is an `Option`, which serde also reads `null` into.
            property = json!({ "anyOf": [property, { "type": "null" }] });
        }
        property["description"] = json!(field.doc.join("\n"));
        if let FieldKind::Default(value) = &field.kind {
            property["default"] = literal(value);
        }
        if matches!(field.kind, FieldKind::Required) {
            required.push(json!(field.name));
        }
        properties.insert(field.name.clone(), property);
    }
    let mut out = json!({
        "type": "object",
        "description": item.doc.join("\n"),
        "properties": properties,
        "additionalProperties": false,
    });
    if !required.is_empty() {
        out["required"] = Json::Array(required);
    }
    if item.deprecated {
        out["deprecated"] = json!(true);
    }
    out
}

/// An enumeration is a string restricted to its item names.
fn enumeration_definition(enumeration: &Enumeration) -> Json {
    let description = enumeration
        .doc
        .clone()
        .unwrap_or_else(|| format!("The `{}` enumeration.", enumeration.name));
    let items: Vec<&str> = enumeration
        .items
        .iter()
        .map(|item| item.name.as_str())
        .collect();
    json!({ "type": "string", "description": description, "enum": items })
}

fn value_schema(ty: &FieldType) -> Json {
    match ty {
        FieldType::Value(value) => value_type_schema(value),
        FieldType::Sourced(value) => json!({
            "type": "object",
            "properties": { "value": value_type_schema(value), "source": { "$ref": SOURCE_REF } },
            "required": ["value", "source"],
            "additionalProperties": false,
        }),
        FieldType::Role(Cardinality::One) => object_id(),
        FieldType::Role(Cardinality::Many) => json!({ "type": "array", "items": object_id() }),
    }
}

fn value_type_schema(value: &ValueType) -> Json {
    match value {
        ValueType::Bool => json!({ "type": "boolean" }),
        // The bounds of the `i64` the Rust types read; serde_json also rejects `2.0`, which
        // JSON Schema counts as an integer, but no keyword can express that.
        ValueType::Integer => {
            json!({ "type": "integer", "minimum": i64::MIN, "maximum": i64::MAX })
        }
        ValueType::Real | ValueType::Quantity(_) => json!({ "type": "number" }),
        ValueType::Text => json!({ "type": "string" }),
        ValueType::Ref(_) => object_id(),
        ValueType::Enum(name) => json!({ "$ref": format!("#/$defs/{name}") }),
        ValueType::List(inner) => json!({ "type": "array", "items": value_type_schema(inner) }),
    }
}

/// A document and clause, each non-empty text.
fn source_definition() -> Json {
    let text = json!({ "type": "string", "minLength": 1 });
    json!({
        "description": "Where a value comes from: the document and clause it is taken from, or the user who entered it.",
        "oneOf": [
            {
                "type": "object",
                "properties": { "document": text, "clause": text },
                "required": ["document", "clause"],
                "additionalProperties": false,
            },
            {
                "type": "object",
                "properties": { "entered_by_user": { "const": true } },
                "required": ["entered_by_user"],
                "additionalProperties": false,
            },
        ],
    })
}

fn object_id() -> Json {
    json!({ "$ref": OBJECT_ID_REF })
}

/// The JSON of a validated default value.
fn literal(value: &Value) -> Json {
    match value {
        Value::Bool(value) => json!(value),
        Value::Integer(value) => json!(value),
        // Validation rejects non-finite defaults; `json!` would turn them into `null`.
        Value::Real(value) => json!(value),
        Value::Text(text) => json!(text),
        Value::List(items) => Json::Array(items.iter().map(literal).collect()),
    }
}

/// Definition names must be distinct and leave [`OBJECT_ID`] free. Validation already keeps
/// field names distinct, and entities, types, property sets and enumerations apart, but a
/// record may still take [`OBJECT_ID`].
fn check_names<'a>(definitions: impl Iterator<Item = &'a str>) -> Result<(), Vec<Error>> {
    let mut names = BTreeSet::from([OBJECT_ID]);
    let errors: Vec<Error> = definitions
        .filter(|name| !names.insert(name))
        .map(|name| {
            let message = format!("two JSON Schema definitions are named `{name}`");
            Error::new(ErrorKind::JsonSchema(message))
        })
        .collect();
    if errors.is_empty() {
        Ok(())
    } else {
        Err(errors)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn maps_value_types() {
        assert_eq!(
            value_type_schema(&ValueType::List(Box::new(ValueType::Enum("Shape".into())))),
            json!({ "type": "array", "items": { "$ref": "#/$defs/Shape" } })
        );
        assert_eq!(
            value_type_schema(&ValueType::Ref("Wall".into())),
            json!({ "$ref": "#/$defs/ObjectId" })
        );
    }

    #[test]
    fn writes_literals() {
        let value = Value::List(vec![
            Value::Bool(true),
            Value::Integer(-3),
            Value::Real(0.5),
            Value::Text("a\"b".into()),
            Value::List(Vec::new()),
        ]);
        assert_eq!(literal(&value), json!([true, -3, 0.5, "a\"b", []]));
    }

    #[test]
    fn rejects_colliding_names() {
        let messages: Vec<String> = check_names([OBJECT_ID, "Wall", "Wall"].into_iter())
            .unwrap_err()
            .iter()
            .map(ToString::to_string)
            .collect();
        assert_eq!(
            messages,
            [
                "two JSON Schema definitions are named `ObjectId`",
                "two JSON Schema definitions are named `Wall`",
            ]
        );
    }
}
