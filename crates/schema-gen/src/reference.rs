//! Reference documentation emitter (COM-04): Markdown pages describing every entity and property
//! set of a namespace, from their `doc` fields and the version history (ADR 0002).

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

use schema::{
    Attribute, Cardinality, Entity, EntityKind, IfcMapping, Namespace, Placement, Presence,
    PropertySet, RoleTarget, Value, ValueType,
};

use crate::Error;

const ENTITIES_PAGE: &str = "entities.md";
const PROPERTY_SETS_PAGE: &str = "property-sets.md";
const NO_ENTITIES: &str = "The schema defines no entities yet.\n";
const NO_PROPERTY_SETS: &str = "The schema defines no property sets yet.\n";

/// The reference pages of a namespace, as Markdown ending with a newline.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ReferencePages {
    /// `index.md`: the namespace and a summary table of its entities and property sets.
    pub index: String,
    /// `entities.md`: every entity, grouped by kind, each under an anchor named after it.
    pub entities: String,
    /// `property-sets.md`: every property set, each under an anchor named after it.
    pub property_sets: String,
}

impl ReferencePages {
    /// Each page with its file name; the pages link to each other by these names.
    #[must_use]
    pub fn files(&self) -> [(&'static str, &str); 3] {
        [
            ("index.md", &self.index),
            (ENTITIES_PAGE, &self.entities),
            (PROPERTY_SETS_PAGE, &self.property_sets),
        ]
    }
}

/// Emits the reference pages of a namespace.
///
/// `snapshots` are the namespace's released versions (`snapshots/NNNN.json`) in version order:
/// an item is documented as introduced in the version from which it has been present without a
/// break, the current one when no snapshot holds it. The namespace is validated first; the same input always gives the same pages.
///
/// # Errors
///
/// Returns validation errors.
pub fn emit_reference(
    namespace: &Namespace,
    snapshots: &[Namespace],
) -> Result<ReferencePages, Vec<Error>> {
    Error::validate(namespace)?;
    let entities = introduced(snapshots, namespace, |version| {
        version.entities.keys().map(String::as_str).collect()
    });
    let property_sets = introduced(snapshots, namespace, |version| {
        version.property_sets.keys().map(String::as_str).collect()
    });
    Ok(ReferencePages {
        index: index_page(namespace),
        entities: entities_page(namespace, &entities),
        property_sets: property_sets_page(namespace, &property_sets),
    })
}

/// The version each item named by `names` has existed since without a break, from the
/// snapshots in version order and then the current namespace: an item removed and added again
/// is dated from its return.
fn introduced<'a>(
    snapshots: &'a [Namespace],
    current: &'a Namespace,
    names: fn(&Namespace) -> BTreeSet<&str>,
) -> BTreeMap<&'a str, u32> {
    let mut since = BTreeMap::new();
    for version in snapshots.iter().chain([current]) {
        let present = names(version);
        since.retain(|name, _| present.contains(name));
        for name in present {
            since.entry(name).or_insert(version.version);
        }
    }
    since
}

fn header(namespace: &Namespace, title: &str) -> String {
    format!(
        "<!-- @generated by schema-gen from the `{}` schema, version {}. Do not edit. -->\n\n# {title}\n",
        namespace.name, namespace.version
    )
}

fn index_page(namespace: &Namespace) -> String {
    let mut out = header(namespace, &format!("The `{}` schema", namespace.name));
    let _ = write!(
        out,
        "\nVersion {} of the `{}` schema: its [entities]({ENTITIES_PAGE}) and \
         [property sets]({PROPERTY_SETS_PAGE}).\n\n## Entities\n\n",
        namespace.version, namespace.name
    );
    if namespace.entities.is_empty() {
        out.push_str(NO_ENTITIES);
    } else {
        header_row(&mut out, &["Entity", "Kind", "Description"]);
        for entity in namespace.entities.values() {
            row(
                &mut out,
                &[
                    &link(&entity.name, ENTITIES_PAGE),
                    entity.kind.name(),
                    &summary(entity),
                ],
            );
        }
    }
    out.push_str("\n## Property sets\n\n");
    if namespace.property_sets.is_empty() {
        out.push_str(NO_PROPERTY_SETS);
    } else {
        header_row(&mut out, &["Property set", "Applies to"]);
        for property_set in namespace.property_sets.values() {
            let name = link(&property_set.name, PROPERTY_SETS_PAGE);
            let applies_to = links(&property_set.applies_to, ENTITIES_PAGE);
            row(&mut out, &[&name, &applies_to]);
        }
    }
    out
}

fn entities_page(namespace: &Namespace, introduced: &BTreeMap<&str, u32>) -> String {
    let mut out = header(namespace, "Entities");
    if namespace.entities.is_empty() {
        out.push('\n');
        out.push_str(NO_ENTITIES);
    }
    for kind in EntityKind::ALL {
        let mut entities = namespace
            .entities
            .values()
            .filter(|entity| entity.kind == kind)
            .peekable();
        if entities.peek().is_none() {
            continue;
        }
        let _ = writeln!(out, "\n## {}", kind_title(kind));
        for entity in entities {
            write_entity(&mut out, entity, since(introduced, &entity.name));
        }
    }
    out
}

/// Every item of the current namespace is in `introduced`.
fn since(introduced: &BTreeMap<&str, u32>, name: &str) -> u32 {
    introduced.get(name).copied().unwrap_or_default()
}

const fn kind_title(kind: EntityKind) -> &'static str {
    match kind {
        EntityKind::Element => "Elements",
        EntityKind::Spatial => "Spatial elements",
        EntityKind::Relationship => "Relationships",
    }
}

fn write_entity(out: &mut String, entity: &Entity, introduced: u32) {
    let _ = writeln!(out, "\n### {}\n", anchored(&entity.name));
    if let Some(doc) = &entity.doc {
        let _ = writeln!(out, "{}\n", prose(doc));
    }
    let _ = writeln!(out, "- **Introduced in:** version {introduced}");
    if let Some(version) = entity.deprecated {
        let _ = writeln!(out, "- **Deprecated since:** version {version}");
    }
    // Validation gives every entity a mapping (CORE-10).
    let mapping = entity.ifc.as_ref().map(ifc_mapping).unwrap_or_default();
    let _ = writeln!(out, "- **IFC:** {mapping}");
    if !entity.property_sets.is_empty() {
        let property_sets = links(&entity.property_sets, PROPERTY_SETS_PAGE);
        let _ = writeln!(out, "- **Property sets:** {property_sets}");
    }
    if let Some(type_def) = &entity.type_def {
        let _ = writeln!(out, "\n#### Type {}\n", anchored(&type_def.name));
        if let Some(doc) = &type_def.doc {
            let _ = write!(out, "{} ", prose(doc));
        }
        let _ = writeln!(
            out,
            "Attributes set on the type are shared by every {} of that type.",
            code(&entity.name)
        );
    }
    if !entity.attributes.is_empty() {
        out.push_str("\n#### Attributes\n\n");
        attribute_table(out, "Attribute", &entity.attributes, "");
    }
    if !entity.roles.is_empty() {
        out.push_str("\n#### Roles\n\n");
        header_row(out, &["Role", "Played by", "Cardinality", "Exclusive"]);
        for role in &entity.roles {
            let targets: Vec<String> = role
                .targets
                .iter()
                .map(|target| match target {
                    RoleTarget::Entity(name) => link(name, ""),
                    RoleTarget::Kind(kind) => format!("any {} entity", kind.name()),
                })
                .collect();
            let cardinality = match role.cardinality {
                Cardinality::One => "one",
                Cardinality::Many => "one or more",
            };
            let exclusive = if role.exclusive { "yes" } else { "no" };
            row(
                out,
                &[
                    &code(&role.name),
                    &targets.join(", "),
                    cardinality,
                    exclusive,
                ],
            );
        }
    }
    if !entity.representations.is_empty() {
        out.push_str("\n#### Representations\n\n");
        header_row(
            out,
            &["Context", "Level of detail", "Depends on", "Generator"],
        );
        for representation in &entity.representations {
            let depends_on: Vec<String> = representation
                .depends_on
                .iter()
                .map(|name| code(name))
                .collect();
            row(
                out,
                &[
                    &code(&representation.context),
                    &representation.lod.to_string(),
                    &depends_on.join(", "),
                    &code(&representation.generator),
                ],
            );
        }
    }
}

fn ifc_mapping(ifc: &IfcMapping) -> String {
    let mut mapping = code(&ifc.entity);
    if let Some(predefined) = &ifc.predefined_type {
        let _ = write!(mapping, ", predefined type {}", code(predefined));
    }
    if let Some(object_type) = &ifc.object_type {
        let _ = write!(mapping, ", object type {}", code(object_type));
    }
    if let Some(type_entity) = &ifc.type_entity {
        let _ = write!(mapping, "; type {}", code(type_entity));
    }
    mapping
}

fn property_sets_page(namespace: &Namespace, introduced: &BTreeMap<&str, u32>) -> String {
    let mut out = header(namespace, "Property sets");
    if namespace.property_sets.is_empty() {
        out.push('\n');
        out.push_str(NO_PROPERTY_SETS);
    }
    for property_set in namespace.property_sets.values() {
        write_property_set(
            &mut out,
            property_set,
            since(introduced, &property_set.name),
        );
    }
    out
}

fn write_property_set(out: &mut String, property_set: &PropertySet, introduced: u32) {
    let _ = writeln!(out, "\n## {}\n", anchored(&property_set.name));
    let _ = writeln!(out, "- **Introduced in:** version {introduced}");
    let _ = writeln!(
        out,
        "- **Applies to:** {}",
        links(&property_set.applies_to, ENTITIES_PAGE)
    );
    if property_set.properties.is_empty() {
        out.push_str("\nThe property set has no properties.\n");
    } else {
        out.push('\n');
        attribute_table(out, "Property", &property_set.properties, ENTITIES_PAGE);
    }
}

/// A table of attributes or properties; `page` is where references to entities link to.
fn attribute_table(out: &mut String, label: &str, attributes: &[Attribute], page: &str) {
    header_row(out, &[label, "Value", "Presence", "Set on", "Description"]);
    for attribute in attributes {
        let presence = match &attribute.presence {
            Presence::Required => "required".to_owned(),
            Presence::Default(value) => format!("default {}", code(&literal(value))),
            Presence::Optional => "optional".to_owned(),
        };
        let placement = match attribute.placement {
            Placement::Instance => "instance",
            Placement::Type => "type",
            Placement::TypeOverridable => "type, instance may override",
        };
        row(
            out,
            &[
                &code(&attribute.name),
                &value_type(&attribute.value, page),
                &presence,
                placement,
                &attribute.doc.as_deref().map(prose).unwrap_or_default(),
            ],
        );
    }
}

fn value_type(value: &ValueType, page: &str) -> String {
    match value {
        ValueType::Bool => "boolean".to_owned(),
        ValueType::Integer => "integer".to_owned(),
        ValueType::Real => "real".to_owned(),
        ValueType::Text => "text".to_owned(),
        ValueType::Enum(name) => format!("enumeration {}", code(name)),
        ValueType::Quantity(kind) => {
            format!("{} ({})", kind.name().replace('_', " "), kind.si_unit())
        }
        ValueType::Ref(name) => format!("reference to {}", link(name, page)),
        ValueType::List(inner) => format!("list of {}", value_type(inner, page)),
    }
}

/// A default value as written in a definition file.
fn literal(value: &Value) -> String {
    match value {
        Value::Bool(value) => value.to_string(),
        Value::Integer(value) => value.to_string(),
        Value::Real(value) => format!("{value:?}"),
        // A JSON string is also a valid TOML basic string.
        Value::Text(text) => serde_json::to_string(text).unwrap_or_default(),
        Value::List(items) => {
            let items: Vec<String> = items.iter().map(literal).collect();
            format!("[{}]", items.join(", "))
        }
    }
}

/// A heading's text, with an anchor named exactly after the item so links survive any
/// renderer's own heading identifiers.
fn anchored(name: &str) -> String {
    format!("<a id=\"{name}\"></a>{name}")
}

/// A link to the anchor of an item on `page`, the current page when empty.
fn link(name: &str, page: &str) -> String {
    format!("[{name}]({page}#{name})")
}

fn links(names: &[String], page: &str) -> String {
    let links: Vec<String> = names.iter().map(|name| link(name, page)).collect();
    links.join(", ")
}

/// The first paragraph of an entity's description, on one line, after its deprecation.
fn summary(entity: &Entity) -> String {
    let paragraph = entity
        .doc
        .as_deref()
        .and_then(|doc| doc.trim().split("\n\n").next())
        .unwrap_or_default();
    let words: Vec<&str> = paragraph.split_whitespace().collect();
    let text = prose(&words.join(" "));
    match entity.deprecated {
        Some(version) => format!("**Deprecated since version {version}.** {text}")
            .trim_end()
            .to_owned(),
        None => text,
    }
}

/// Description text, kept as Markdown but unable to inject HTML.
fn prose(text: &str) -> String {
    text.trim().replace('&', "&amp;").replace('<', "&lt;")
}

/// `text` as inline code, fenced with more backticks than it holds in a row.
fn code(text: &str) -> String {
    let longest = text
        .split(|character| character != '`')
        .map(str::len)
        .max()
        .unwrap_or(0);
    let fence = "`".repeat(longest + 1);
    let pad = if text.starts_with('`') || text.ends_with('`') {
        " "
    } else {
        ""
    };
    format!("{fence}{pad}{text}{pad}{fence}")
}

/// A table's header row and the separator under it.
fn header_row(out: &mut String, titles: &[&str]) {
    row(out, titles);
    row(out, &vec!["---"; titles.len()]);
}

/// A table row; pipes and line breaks in a cell would end it early.
fn row(out: &mut String, cells: &[&str]) {
    out.push('|');
    for cell in cells {
        let cell = cell.replace('|', "\\|").replace('\n', "<br>");
        let _ = write!(out, " {cell} |");
    }
    out.push('\n');
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::{ErrorKind, Source, parse_sources};

    /// A namespace at `version` with the given extra definition files.
    fn namespace(version: u32, files: &[(&str, &str)]) -> Namespace {
        let mut sources = vec![Source {
            path: "namespace.toml".into(),
            contents: format!("format = 1\n[namespace]\nname = \"core\"\nversion = {version}\n"),
        }];
        sources.extend(files.iter().map(|(path, contents)| Source {
            path: (*path).into(),
            contents: (*contents).into(),
        }));
        parse_sources(&sources).unwrap()
    }

    const STOREY: (&str, &str) = (
        "entities/storey.toml",
        "format = 1\n[entity]\nname = \"Storey\"\nkind = \"spatial\"\n[ifc]\nentity = \"IfcBuildingStorey\"\n",
    );
    const SPACE: (&str, &str) = (
        "entities/space.toml",
        "format = 1\n[entity]\nname = \"Space\"\nkind = \"spatial\"\ndeprecated = 2\n[ifc]\nentity = \"IfcSpace\"\n",
    );

    const SPACE_V1: (&str, &str) = (
        "entities/space.toml",
        "format = 1\n[entity]\nname = \"Space\"\nkind = \"spatial\"\ndeprecated = 1\n[ifc]\nentity = \"IfcSpace\"\n",
    );

    #[test]
    fn dates_items_from_the_first_snapshot_holding_them() {
        let v1 = namespace(1, &[STOREY]);
        let v2 = namespace(2, &[STOREY, SPACE]);
        let current = namespace(3, &[STOREY, SPACE]);
        let pages = emit_reference(&current, &[v1, v2]).unwrap();
        let storey = pages.entities.find("Storey\n").unwrap();
        let space = pages.entities.find("Space\n").unwrap();
        assert!(pages.entities[storey..].contains("Introduced in:** version 1"));
        assert!(pages.entities[space..storey].contains("Introduced in:** version 2"));
        assert!(pages.entities[space..storey].contains("Deprecated since:** version 2"));
    }

    #[test]
    fn dates_items_added_again_from_their_return() {
        let v1 = namespace(1, &[STOREY]);
        let v2 = namespace(2, &[]);
        let pages = emit_reference(&namespace(3, &[STOREY]), &[v1, v2]).unwrap();
        assert!(pages.entities.contains("Introduced in:** version 3"));
    }

    #[test]
    fn summarises_the_first_paragraph_and_deprecation() {
        let wrapped = (
            "entities/zone.toml",
            "format = 1\n[entity]\nname = \"Zone\"\nkind = \"spatial\"\ndeprecated = 1\ndoc = \"\"\"\nA group\nof spaces.\n\nMore.\"\"\"\n[ifc]\nentity = \"IfcZone\"\n",
        );
        let pages = emit_reference(&namespace(1, &[wrapped, SPACE_V1]), &[]).unwrap();
        assert!(
            pages
                .index
                .contains("| **Deprecated since version 1.** A group of spaces. |")
        );
        assert!(pages.index.contains("| **Deprecated since version 1.** |"));
    }

    #[test]
    fn dates_unreleased_items_with_the_current_version() {
        let pages = emit_reference(&namespace(4, &[STOREY]), &[]).unwrap();
        assert!(pages.entities.contains("Introduced in:** version 4"));
    }

    #[test]
    fn documents_sparse_items() {
        let plain = (
            "entities/zone.toml",
            "format = 1\n[entity]\nname = \"Zone\"\nkind = \"spatial\"\n[ifc]\nentity = \"IfcZone\"\n[[attribute]]\nname = \"ratio\"\nvalue = \"real\"\n",
        );
        let empty = (
            "property-sets/empty.toml",
            "format = 1\n[property_set]\nname = \"Pset_Empty\"\napplies_to = [\"Zone\"]\n",
        );
        let pages = emit_reference(&namespace(1, &[plain, empty]), &[]).unwrap();
        assert!(pages.entities.contains("- **IFC:** `IfcZone`\n"));
        assert!(pages.entities.contains("| `ratio` | real |"));
        assert!(pages.property_sets.contains("has no properties"));
    }

    #[test]
    fn says_when_the_schema_is_empty() {
        let pages = emit_reference(&namespace(1, &[]), &[]).unwrap();
        assert!(pages.index.contains("no entities yet"));
        assert!(pages.index.contains("no property sets yet"));
        assert!(pages.entities.contains("no entities yet"));
        assert!(pages.property_sets.contains("no property sets yet"));
    }

    #[test]
    fn rejects_invalid_namespaces() {
        let mut invalid = namespace(1, &[]);
        invalid.name = String::new();
        assert!(matches!(
            emit_reference(&invalid, &[]).unwrap_err()[0].kind,
            ErrorKind::Validation(_)
        ));
    }

    #[test]
    fn escapes_html_and_table_breaks() {
        assert_eq!(prose(" a < b & c "), "a &lt; b &amp; c");
        let mut out = String::new();
        row(&mut out, &["a|b", "c\nd"]);
        assert_eq!(out, "| a\\|b | c<br>d |\n");
    }

    #[test]
    fn fences_code_around_backticks() {
        assert_eq!(code("x"), "`x`");
        assert_eq!(code("a`b"), "``a`b``");
        assert_eq!(code("`a``"), "``` `a`` ```");
    }

    #[test]
    fn writes_literals() {
        let value = Value::List(vec![
            Value::Bool(true),
            Value::Integer(-3),
            Value::Real(2.0),
            Value::Text("a\"b\u{1b}".into()),
        ]);
        assert_eq!(literal(&value), r#"[true, -3, 2.0, "a\"b\u001b"]"#);
    }

    #[test]
    fn describes_value_types() {
        let list = ValueType::List(Box::new(ValueType::Ref("Wall".into())));
        assert_eq!(
            value_type(&list, ENTITIES_PAGE),
            "list of reference to [Wall](entities.md#Wall)"
        );
        assert_eq!(
            value_type(&ValueType::Enum("Side".into()), ""),
            "enumeration `Side`"
        );
        assert_eq!(
            value_type(
                &ValueType::Quantity(schema::QuantityKind::ThermalTransmittance),
                ""
            ),
            "thermal transmittance (W/(m²·K))"
        );
    }
}
